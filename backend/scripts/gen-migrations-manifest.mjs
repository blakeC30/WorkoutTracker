#!/usr/bin/env node
//
// Writes src/lib/migrations-manifest.ts from the filenames in migrations/.
//
// Why generate a file instead of reading the directory at request time: migrations/*.sql is
// not imported by any route, so Vercel's file tracing has no reason to bundle it into the
// serverless function. The directory read would work locally and return an empty list in
// production — the worst kind of wrong, because the health check would then cheerfully
// report zero pending migrations forever.
//
// Runs automatically before `npm run build` and `npm run dev` via npm's pre* hooks. The
// output is committed so the repo typechecks on a fresh clone, and regenerated on every
// build so a stale commit cannot outlive the next deploy.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const BACKEND_DIR = path.resolve(fileURLToPath(import.meta.url), '../..');
const MIGRATIONS_DIR = path.join(BACKEND_DIR, 'migrations');
const OUT_FILE = path.join(BACKEND_DIR, 'src', 'lib', 'migrations-manifest.ts');

const files = (await readdir(MIGRATIONS_DIR)).filter((f) => f.endsWith('.sql')).sort();

const body = `// GENERATED by scripts/gen-migrations-manifest.mjs — do not edit.
//
// The migrations this build of the code expects to be applied. /api/health compares it
// against the schema_migrations table so a deploy that outran \`npm run migrate:prod\` is
// visible immediately, rather than surfacing later as a query against a column that is not
// there yet.

export const EXPECTED_MIGRATIONS: readonly string[] = [
${files.map((f) => `  '${f}',`).join('\n')}
];
`;

// Only write when the content actually changed. An unconditional write churns the file's
// mtime on every dev server start, which shows up as a phantom change in editors and as a
// needless rebuild trigger.
let existing = null;
try {
  existing = await readFile(OUT_FILE, 'utf8');
} catch {
  // Not generated yet.
}

if (existing === body) {
  console.log(`migrations manifest up to date (${files.length} migration(s))`);
} else {
  await writeFile(OUT_FILE, body);
  console.log(`wrote src/lib/migrations-manifest.ts (${files.length} migration(s))`);
}
